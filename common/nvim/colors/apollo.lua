for severity, foreground in pairs({ Error = "red", Warn = "amber", Info = "teal", Hint = "green", Ok = "green" }) do
	for _, prefix in ipairs({ "Diagnostic", "DiagnosticSign", "DiagnosticFloating", "DiagnosticVirtualText" }) do
		colorbuddy.Group.new(prefix .. severity, color(foreground), colors.none, styles.NONE)
	end
	vim.api.nvim_set_hl(0, "DiagnosticUnderline" .. severity, { undercurl = true, sp = palette[foreground] })
end
